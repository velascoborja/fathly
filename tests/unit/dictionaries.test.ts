    expect(dictionaries.es.dashboard.monthlyResult).toBe("Resultado mensual")
    expect(dictionaries.es.dashboard.monthlyResultSurplus).toBe("Restante tras gastos")
    expect(dictionaries.es.dashboard.monthlyResultLowMargin).toBe("Margen mínimo")
    expect(dictionaries.es.dashboard.coverageMarginMarker).toBe("Margen mínimo seleccionado")
    expect(dictionaries.es.settings.lowMonthlyMarginPercent).toBe("Margen mínimo de resultado mensual")
    expect(dictionaries.es.settings.shareAccessCardTitle).toBe("Compartir acceso")
    expect(dictionaries.es.settings.membersTitle).toBe("Personas con acceso")
    expect(dictionaries.es.settings.deleteAccountAction).toBe("Eliminar cuenta")
    expect(dictionaries.es.settings.deleteAccountDialogDescription).toContain("No se puede deshacer")
    expect(dictionaries.es.setup.title).toBe("Asistente inicial de presupuesto")
    expect(dictionaries.es.setup.subtitle).toBe("Añade hasta 2 ingresos mensuales y 2 gastos mensuales para crear el panel. Después podrás completar el resto desde el dashboard.")
    expect(dictionaries.es.setup.stepExpensesBody).toBe("Registra al menos un gasto mensual para activar el panel.")
    expect(dictionaries.es.setup.incomeNameLabel).toBe("Fuente de ingreso")
    expect(dictionaries.es.setup.expenseAmountLabel).toBe("Gasto mensual")
    expect(dictionaries.es.setup.finish).toBe("Crear mi panel")
    expect(dictionaries.es.setup.limitHint).toContain("Máximo 2")
    expect(dictionaries.es.setup.requiredHint).toContain("1 ingreso")
    expect(dictionaries.es.setup).not.toHaveProperty("annualCostsTitle")
    expect(dictionaries.es.dashboard.categoryTotal).toBe("Total")
    expect(dictionaries.es.dashboard.largest).toBe("Mayores gastos")
    expect(dictionaries.es.dashboard).not.toHaveProperty("commandCenter")
    expect(dictionaries.es.actions.editDeposit).toBe("Editar ingreso")
    expect(dictionaries.es.actions.editCommitment).toBe("Editar gasto")
    expect(dictionaries.es.actions.collapseCategory).toBe("Contraer")
    expect(dictionaries.es.actions.expandCategory).toBe("Expandir")
    expect(dictionaries.es.actions.deleteConfirmation).toContain("{name}")
    expect(dictionaries.es.monthlyBills.subtitle).toBe("Añade y revisa los gastos mensuales compartidos de la casa.")
    expect(dictionaries.es.annualCosts.subtitle).toBe("Registra los gastos anuales para prorratearlos mes a mes en el presupuesto familiar.")

    expect(dictionaries.en.dashboard.title).toBe("Monthly summary")
    expect(dictionaries.en.dashboard.subtitle).toBe("Review the month across income and expenses.")
    expect(dictionaries.en.dashboard.covered).toBe("of budget used")
    expect(dictionaries.en.dashboard.commitments).toBe("Shared expenses")
    expect(dictionaries.en.dashboard.breakdown).toBe("Breakdown by expense")
    expect(dictionaries.en.dashboard.monthOutflows).toBe("Monthly outflows")
    expect(dictionaries.en.dashboard.monthlyResult).toBe("Monthly result")
    expect(dictionaries.en.dashboard.monthlyResultSurplus).toBe("Left after expenses")
    expect(dictionaries.en.dashboard.monthlyResultLowMargin).toBe("Minimum margin")
    expect(dictionaries.en.dashboard.coverageMarginMarker).toBe("Selected minimum margin")
    expect(dictionaries.en.settings.lowMonthlyMarginPercent).toBe("Minimum monthly result margin")
    expect(dictionaries.en.settings.shareAccessCardTitle).toBe("Share access")
    expect(dictionaries.en.settings.membersTitle).toBe("People with access")
    expect(dictionaries.en.settings.deleteAccountAction).toBe("Delete account")
    expect(dictionaries.en.settings.deleteAccountDialogDescription).toContain("cannot be undone")
    expect(dictionaries.en.setup.title).toBe("Initial budget assistant")
    expect(dictionaries.en.setup.subtitle).toBe("Add up to 2 monthly income items and 2 monthly expenses to create the dashboard. You can finish the rest from the dashboard later.")
    expect(dictionaries.en.setup.stepExpensesBody).toBe("Register at least one monthly expense to enable the dashboard.")
    expect(dictionaries.en.setup.incomeNameLabel).toBe("Income source")
    expect(dictionaries.en.setup.expenseAmountLabel).toBe("Monthly expense")
    expect(dictionaries.en.setup.finish).toBe("Create my dashboard")
    expect(dictionaries.en.setup.limitHint).toContain("Maximum 2")
    expect(dictionaries.en.setup.requiredHint).toContain("1 income")
    expect(dictionaries.en.setup).not.toHaveProperty("annualCostsTitle")
    expect(dictionaries.en.dashboard.categoryTotal).toBe("Total")
    expect(dictionaries.en.dashboard.largest).toBe("Largest expenses")
    expect(dictionaries.en.dashboard).not.toHaveProperty("commandCenter")
    expect(dictionaries.en.actions.editDeposit).toBe("Edit income")
